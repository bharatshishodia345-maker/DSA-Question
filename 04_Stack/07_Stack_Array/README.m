# Stack Implementation Using Array

## 📌 Objective

Implemented a Stack data structure using a Python list (array).

## 🧠 Stack Operations

### Push

Adds an element to the top of the Stack.

### Pop

Removes the top element from the Stack.

### Traverse

Displays all elements currently present in the Stack.

## ⚠️ Stack Conditions

### Stack Overflow

Occurs when we try to push an element into a full Stack.

### Stack Underflow

Occurs when we try to pop an element from an empty Stack.

## 💻 Concepts Used

- Array/List
- Stack
- LIFO (Last In, First Out)
- Push
- Pop
- Traverse
- Overflow
- Underflow

## 🛠️ Language

Python 3

## 🎯 Learning Outcome

Learned how to implement a Stack using an array and handle Stack overflow and underflow conditions.